-- ============================================================
-- 088: 評価ごとの「水色の名前」を保存する
--
-- これまで水色の名前はカラーパレット（tea_colors）との色コード照合でしか
-- 決まらなかったため、パレットに無い色を使うと評価カードが必ず
-- 「カスタム」と表示されてしまっていた。
--
-- パレットに登録しなくても名前を付けられるように、評価側に列を持たせる。
-- 表示の優先順位は次のとおり（アプリ側で実装）:
--   ① reviews.color_name（利用者が付けた名前）
--   ② カラーパレットの色名（色コードが一致する場合）
--   ③ 「カスタム」
-- ============================================================

alter table public.reviews
  add column if not exists color_name text;

comment on column public.reviews.color_name is
  '水色に付けた名前。パレット未登録の色でも評価カードに名前を表示するために使う';
